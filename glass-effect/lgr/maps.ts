/** Decoded-blob URL cache (per mode, never revoked — see slg/mapUrl.ts). */
const blobUrls = new Map<LgrMode, string>()

/** Decode an upstream map into a blob: URL suitable for <feImage href>. */
export function lgrMapUrl(mode: LgrMode): string {
  const hit = blobUrls.get(mode)
  if (hit) return hit
  const { mime, base64 } = DATA_URIS[mode]
  const binary = atob(base64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  const url = URL.createObjectURL(new Blob([bytes], { type: mime }))
  blobUrls.set(mode, url)
  return url
}
